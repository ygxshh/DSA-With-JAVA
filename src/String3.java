public class String3 {
    public static void main(String[] args) {
        float a = 453.127f;
        System.out.printf("%.2f",a); // use it for when you want decimal upto digits, it also round off!
        System.out.println();
        float b = 453.123f;
        System.out.printf(("%.2f"),b);

        System.out.println();

        System.out.printf("%.3f", Math.PI);
    }
}
